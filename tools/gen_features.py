#!/usr/bin/env python3
"""Build features.html from index.html (head, header, footer, shared script, download block)
and tools/features_main.html (the page body, ROI and accuracy blocks in tools/features_parts/).

Run after any change to index.html:  python3 tools/gen_features.py
Feature cards are not copied: they are rendered from MODS in the shared script, so a new card
added to MODS shows up here too. Put its key into a group in FGK (index.html) — otherwise it
lands in the "More" group.
"""
import io, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rd = lambda p: io.open(os.path.join(ROOT, p), encoding="utf-8").read()
idx = rd("index.html")
tpl = rd("tools/features_main.html")


def between(s, a, b, inclusive=True):
    i = s.index(a)
    j = s.index(b, i) + len(b)
    return s[i:j] if inclusive else s[i + len(a):j - len(b)]


def one(s, old, new):
    if s.count(old) != 1:
        sys.exit("gen_features: expected exactly one %r (found %d)" % (old[:70], s.count(old)))
    return s.replace(old, new)


head_end = idx.index('<main id="top">')
top = idx[:head_end]
rest = idx[idx.index('</main>'):]
get = between(idx, '  <!-- FINAL CTA -->', '</section>\n')

# ---- head ----
TITLE = "InCost Features — Sheet Metal, Laser, 3D Printing and Machining Quoting for Windows"
DESC = ("Every InCost feature in one place: DXF and PDF drawing to price, nesting, cutting simulation, "
        "slicer time and grams for 3D printing, drawings from 3D models, engineer calculators, quotes and shop tools.")
top = re.sub(r"<title>.*?</title>", "<title>%s</title>" % TITLE, top, count=1)
top = re.sub(r'<meta name="description" content="[^"]*">', '<meta name="description" content="%s">' % DESC, top, count=1)
top = one(top, '<link rel="canonical" href="https://incost.app/">', '<link rel="canonical" href="https://incost.app/features.html">')
top = one(top, '<meta property="og:url" content="https://incost.app/">', '<meta property="og:url" content="https://incost.app/features.html">')
top = re.sub(r'<meta property="og:title" content="[^"]*">', '<meta property="og:title" content="InCost — all features">', top, count=1)
top = re.sub(r'<script type="application/ld\+json">.*?</script>\n?', "", top, count=1, flags=re.S)

# ---- header links point back to the home page ----
top = one(top, '<a class="logo" href="#top"', '<a class="logo" href="./"')
for sec in ("how", "tools", "pricing", "faq", "contact"):
    top = top.replace('<li><a href="#%s"' % sec, '<li><a href="index.html#%s"' % sec)
top = one(top, '<li><a href="features.html" data-i="nav.features">', '<li><a href="features.html" aria-current="page" data-i="nav.features">')

# ---- footer links ----
foot = between(rest, "<footer>", "</footer>")
foot2 = re.sub(r'href="#(?!get")([a-z]+)"', r'href="index.html#\1"', foot)
rest = rest.replace(foot, foot2)

parts = os.path.join(ROOT, "tools", "features_parts")
body = tpl.replace("@@ROI@@", rd("tools/features_parts/roi.html").rstrip("\n") + "\n") \
          .replace("@@ACC@@", rd("tools/features_parts/accuracy.html").rstrip("\n") + "\n") \
          .replace("@@GET@@", get.rstrip("\n") + "\n")

out = top + '<main id="top">\n' + body + rest
banner = "<!-- generated by tools/gen_features.py from index.html — edit index.html or tools/features_main.html, then re-run -->\n"
out = out.replace("<!doctype html>\n", "<!doctype html>\n" + banner, 1)
io.open(os.path.join(ROOT, "features.html"), "w", encoding="utf-8").write(out)
print("features.html", len(out), "bytes")
